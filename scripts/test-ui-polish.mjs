import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {existsSync} from 'node:fs';
import {chromium} from 'playwright';

const chrome=['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const browser=await chromium.launch({headless:true,...(chrome?{executablePath:chrome}:{})});
const output='artifacts/ui-polish';
await fs.mkdir(output,{recursive:true});
const report=[];
try{
 for(const [label,width,height] of [['desktop',1440,900],['tablet',768,1024],['mobile',390,844],['small-mobile',360,800]]){
  const page=await browser.newPage({viewport:{width,height},deviceScaleFactor:1});
  page.setDefaultTimeout(12000);
  await page.route('https://**/*',route=>route.abort());
  const errors=[];
  const failed=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('requestfailed',request=>failed.push(request.url()));
  await page.addInitScript(()=>localStorage.setItem('bobot:v1:guestCart',JSON.stringify([{key:'ui-polish-fixture',productId:'ui-polish-fixture',itemId:'ui-polish-fixture',collectionId:'bakeryproducts',quantity:1,unitPrice:55000,productNameSnapshot:'Red Velvet Cream Cheese Brownie',image:'assets/maison-v4/strawberry-chiffon.webp'}])));
  await page.goto('http://127.0.0.1:4173/menu.html',{waitUntil:'domcontentloaded'});
  console.log(label,'menu loaded');
  await page.locator('#cart-drawer').waitFor({state:'attached'});
  await page.locator('.cart-line').first().waitFor({state:'attached'});
  console.log(label,'cart ready');
  await page.screenshot({path:`${output}/${label}-menu.png`,fullPage:true,timeout:12000,animations:'disabled'});
  console.log(label,'menu captured');
  await page.evaluate(async()=>{const cart=await import('/js/services/cartService.js');cart.openCart();});
  await page.locator('#cart-drawer[open]').waitFor();
  await page.screenshot({path:`${output}/${label}-cart.png`,timeout:12000,animations:'disabled'});
  const cartState=await page.evaluate(()=>{const dialog=document.querySelector('#cart-drawer');const footer=dialog.querySelector('.cart-drawer__footer').getBoundingClientRect();const button=dialog.querySelector('#cart-checkout');return{overflow:document.documentElement.scrollWidth-innerWidth,footerBottom:footer.bottom,viewport:innerHeight,buttonBackground:getComputedStyle(button).backgroundColor,buttonDisabled:button.disabled,itemCount:dialog.querySelectorAll('.cart-line').length};});
  assert.ok(cartState.overflow<=1,`${label}: horizontal overflow`);
  assert.ok(cartState.footerBottom<=height+1,`${label}: footer clipped`);
  assert.equal(cartState.itemCount,1);
  assert.equal(cartState.buttonDisabled,false);
  assert.equal(cartState.buttonBackground,'rgb(48, 36, 30)');
  await page.locator('[data-cart-plus]').click();
  assert.equal(await page.locator('.cart-line__actions span').innerText(),'2');
  await page.locator('[data-cart-minus]').click();
  assert.equal(await page.locator('.cart-line__actions span').innerText(),'1');
  await page.evaluate(async()=>{const {toast}=await import('/js/core/toast.js');toast({title:'Đã thêm vào giỏ',description:'Bánh đã thêm',variant:'success'});});
  assert.equal(await page.locator('.toast--success').count(),1);
  assert.equal(await page.locator('.toast--success').isVisible(),true);
  const toastState=await page.evaluate(()=>{const toast=document.querySelector('.toast--success').getBoundingClientRect();const footer=document.querySelector('.cart-drawer__footer').getBoundingClientRect();return{toastBottom:toast.bottom,footerTop:footer.top};});
  assert.ok(toastState.toastBottom<toastState.footerTop,`${label}: toast covers cart actions`);
  await page.screenshot({path:`${output}/${label}-toast.png`,timeout:12000,animations:'disabled'});
  await page.evaluate(async()=>{const {toast}=await import('/js/core/toast.js');toast({title:'Không thể thêm',variant:'destructive'});});
  assert.equal(await page.locator('.toast--destructive[role="alert"]').count(),1);
  assert.equal(await page.locator('.toast--destructive').isVisible(),true);
  await page.evaluate(async()=>{const {initCheckoutForm}=await import('/js/components/checkout-form.js');const dialog=await initCheckoutForm();document.querySelector('#cart-drawer').close();dialog.showModal();});
  await page.locator('#checkout-dialog[open]').waitFor();
  assert.equal(await page.locator('.checkout-geocoder-notice').isVisible(),false);
  assert.equal(await page.locator('#checkout-submit').innerText(),'Xác Nhận Đặt Bánh');
  await page.screenshot({path:`${output}/${label}-checkout.png`,timeout:12000,animations:'disabled'});
  await page.locator('.checkout-summary').scrollIntoViewIfNeeded();
  await page.screenshot({path:`${output}/${label}-checkout-summary.png`,timeout:12000,animations:'disabled'});
  await page.locator('input[name="fulfillmentType"][value="delivery"]').check();
  assert.equal(await page.locator('#checkout-verify').isVisible(),true);
  await page.locator('input[name="fulfillmentType"][value="pickup"]').check();
  assert.equal(await page.locator('#checkout-shipping').isVisible(),false);
  const checkoutState=await page.evaluate(()=>({dialogWidth:document.querySelector('#checkout-dialog').getBoundingClientRect().width,viewport:innerWidth,overflow:document.documentElement.scrollWidth-innerWidth}));
  assert.ok(checkoutState.dialogWidth<=width+1);
  assert.ok(checkoutState.overflow<=1);
  await page.locator('#checkout-dialog header [data-close]').click();
  await page.evaluate(async()=>{const cart=await import('/js/services/cartService.js');cart.openCart();});
  await page.locator('#cart-drawer[open]').waitFor();
  await page.locator('#cart-clear').click();
  assert.equal(await page.locator('.cart-empty').count(),1);
  assert.equal(await page.locator('#cart-checkout').isDisabled(),true);
  report.push({label,cartState,checkoutState,errors,failed:[...new Set(failed)]});
  await page.close();
 }
}finally{await browser.close();}
await fs.writeFile(`${output}/report.json`,JSON.stringify(report,null,2));
for(const row of report)console.log(JSON.stringify(row));
